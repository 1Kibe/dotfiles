-- The files next to this one that are not modules (the shell's generated
-- ones, this machine's local.lua) are read from this folder by their exact
-- path, as text only: never through package.path, which also looks in the
-- current folder (the home), so a stray file there is never run. A missing
-- file is normal (a new install, before the shell runs) and says nothing;
-- any other error goes to the log and the rest of the config stays. `env`:
-- what the file may use (nil: everything, for local.lua)
local config_dir = package.path:match("^([^;]+)/%?%.lua")
  or ((os.getenv("XDG_CONFIG_HOME") or ((os.getenv("HOME") or "") .. "/.config")) .. "/hypr")
local function load_beside(name, env)
  local path = config_dir .. "/" .. name .. ".lua"
  local f = io.open(path, "rb")
  if not f then
    return
  end
  f:close()
  -- An explicit nil would still replace the globals: pass env only when given
  local chunk, err
  if env then
    chunk, err = loadfile(path, "t", env)
  else
    chunk, err = loadfile(path, "t")
  end
  if chunk then
    local ok, rerr = pcall(chunk)
    err = not ok and rerr or nil
  end
  if err then
    print("hyprland.lua: " .. name .. ".lua: " .. tostring(err))
  end
end

-- The shell's settings (Configurações), generated by Quickshell
-- (state/SettingsApply) into dotfiles_settings.lua, ignored by git. It may
-- only call the Hyprland functions it writes and set the areas' table
-- (modules/areas.lua reads dotfiles_areas), nothing else
local settings = { hl = { config = hl.config, env = hl.env, layer_rule = hl.layer_rule } }
load_beside("dotfiles_settings", settings)
if type(settings.dotfiles_areas) == "table" then
  dotfiles_areas = settings.dotfiles_areas
end

-- The screens' arrangement (Configurações → Monitores), generated by the
-- shell into dotfiles_monitors.lua, ignored by git; missing is normal, like
-- dotfiles_settings above. local.lua comes after it and wins
-- 4 fingers sideways, now that the settings say the areas' mode
require("modules.areas").gestures()

-- Only hl.monitor(), one per screen
load_beside("dotfiles_monitors", { hl = { monitor = hl.monitor } })

-- Never without a screen: half a second after a reload or a screen going
-- away, if no real screen is on, every known one is turned on with
-- Hyprland's own choices ("disabled = false" said out loud: a rule that
-- turned it off stays until another says so). Hyprland's FALLBACK (the
-- stand-in it makes when no screen is left) does not count and is never
-- turned on here. With any real screen on it does nothing; turning a
-- screen on never sends monitor.removed, so it cannot call itself again
local function keep_a_screen()
  local all = hl.get_monitors({ all = true }) or {}
  for _, m in ipairs(all) do
    if m.enabled and m.name ~= "FALLBACK" then
      return
    end
  end
  for _, m in ipairs(all) do
    if m.name ~= "FALLBACK" then
      hl.monitor({ output = m.name, disabled = false, mode = "preferred", position = "auto", scale = "auto" })
    end
  end
end
local function check_screens_soon()
  -- No screen known: nothing to look after (also Hyprland's config check,
  -- which has no event loop: a timer there crashes it)
  if #(hl.get_monitors({ all = true }) or {}) == 0 then
    return
  end
  hl.timer(keep_a_screen, { timeout = 500, type = "oneshot" })
end
hl.on("config.reloaded", check_screens_soon)
hl.on("monitor.removed", check_screens_soon)

-- Optional: a missing local.lua is not an error. Last, so this machine wins.
-- This machine's own Lua: everything is allowed
load_beside("local")
