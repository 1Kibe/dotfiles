-- Hyprland config (Lua, Hyprland 0.55+). One module per subject; local.lua
-- (ignored by git) holds machine-specific settings and loads last, so it can
-- override anything. Keybinds and gestures: hyprland/README.md or Super+F1.

-- Any monitor: preferred mode, automatic position and scale.
-- Real monitors and scales go in local.lua.
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "auto" })

require("modules.env")
require("modules.look")
require("modules.input")
require("modules.rules")
require("modules.keybinds")
require("modules.autostart")

-- The shell's settings (Configurações → Aparência), generated by Quickshell
-- (state/SettingsApply) into dotfiles_settings.lua, ignored by git. A missing
-- file is normal (a new install, before the shell runs); any other error goes
-- to the log and the modules' values stay
local ok, err = pcall(require, "dotfiles_settings")
if not ok and not tostring(err):find("module 'dotfiles_settings' not found", 1, true) then
  print("hyprland.lua: dotfiles_settings.lua: " .. tostring(err))
end

-- Optional: a missing local.lua is not an error. Last, so this machine wins
pcall(require, "local")
