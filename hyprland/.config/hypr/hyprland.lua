-- Never without a screen: half a second after a reload or a screen going
-- away, if no real screen is on, every known one is turned on with
-- Hyprland's own choices ("disabled = false" said out loud: a rule that
-- turned it off stays until another says so). Hyprland's FALLBACK (the
-- stand-in it makes when no screen is left) does not count and is never
-- turned on here. With any real screen on it does nothing; turning a
-- screen on never sends monitor.removed, so it cannot call itself again
local function keep_a_screen()
  local all = hl.get_monitors({ all = true }) or {}
  for _, m in ipairs(all) do
    if m.enabled and m.name ~= "FALLBACK" then
      return
    end
  end
  for _, m in ipairs(all) do
    if m.name ~= "FALLBACK" then
      hl.monitor({ output = m.name, disabled = false, mode = "preferred", position = "auto", scale = "auto" })
    end
  end
end
local function check_screens_soon()
  -- No screen known: nothing to look after (also Hyprland's config check,
  -- which has no event loop: a timer there crashes it)
  if #(hl.get_monitors({ all = true }) or {}) == 0 then
    return
  end
  hl.timer(keep_a_screen, { timeout = 500, type = "oneshot" })
end
hl.on("config.reloaded", check_screens_soon)
hl.on("monitor.removed", check_screens_soon)

