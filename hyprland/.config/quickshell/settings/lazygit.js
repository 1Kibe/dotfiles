// lazygit's and delta's colors from the shell's theme, next to lazygit's own
// config (common/.config/lazygit/config.yml, which has no color): tema.yml,
// read after it (LG_CONFIG_FILE lists both, ~/.config/bash/dotfiles.bash),
// and delta.gitconfig, the [delta] options the diff renderer is pointed at
// (delta --config). Plain JS: read by the shell (state/SettingsApply) and by
// the tests. Every color is checked as "#rrggbb" first: a bad one throws and
// nothing is written.

function isHex(c) {
    return typeof c === "string" && /^#[0-9a-fA-F]{6}$/.test(c)
}
function hex(colors, role) {
    const c = String(colors[role]).toLowerCase()
    if (!Object.prototype.hasOwnProperty.call(colors, role) || !isHex(c))
        throw new Error(`lazygit: cor inválida (${role})`)
    return c
}
// a mixed t of the way to b
function mix(a, b, t) {
    const pa = [1, 3, 5].map(i => parseInt(a.substr(i, 2), 16))
    const pb = [1, 3, 5].map(i => parseInt(b.substr(i, 2), 16))
    return "#" + pa.map((v, i) => Math.round(v + (pb[i] - v) * t).toString(16).padStart(2, "0")).join("")
}

// lazygit option -> [Theme role, extra attributes]
var THEME = [
    ["activeBorderColor", "accentLight", ["bold"]],
    ["inactiveBorderColor", "bg2", []],
    ["searchingActiveBorderColor", "yellow", ["bold"]],
    ["optionsTextColor", "blue", []],
    ["selectedLineBgColor", "bg1", []],
    ["inactiveViewSelectedLineBgColor", "bg1", []],
    ["cherryPickedCommitFgColor", "bg2", []],
    ["cherryPickedCommitBgColor", "aqua", []],
    ["markedBaseCommitFgColor", "bg2", []],
    ["markedBaseCommitBgColor", "yellow", []],
    ["unstagedChangesColor", "red", []],
    ["defaultFgColor", "fg", []]
]

// `colors`: role -> "#rrggbb" (the Theme's)
function themeYaml(colors) {
    const lines = [
        "# Generated by the shell from its theme (Configurações → Tema): rewritten",
        "# on every change. lazygit reads it after config.yml.",
        "gui:",
        "  theme:"
    ]
    for (const [option, role, extra] of THEME)
        lines.push(`    ${option}: [${["'" + hex(colors, role) + "'"].concat(extra).join(", ")}]`)
    return lines.join("\n") + "\n"
}

function deltaConf(colors) {
    const bg = hex(colors, "bgHard")
    const red = hex(colors, "red")
    const green = hex(colors, "green")
    const q = c => `"${c}"`
    const lines = [
        "# Generated by the shell from its theme (Configurações → Tema): rewritten",
        "# on every change. lazygit's diff renderer reads it (delta --config).",
        "[delta]",
        "    syntax-theme = gruvbox-dark",
        "    line-numbers = true",
        `    minus-style = syntax ${q(mix(red, bg, 0.78))}`,
        `    minus-emph-style = syntax ${q(mix(red, bg, 0.55))}`,
        `    plus-style = syntax ${q(mix(green, bg, 0.8))}`,
        `    plus-emph-style = syntax ${q(mix(green, bg, 0.6))}`,
        `    line-numbers-minus-style = ${q(red)}`,
        `    line-numbers-plus-style = ${q(green)}`,
        `    line-numbers-zero-style = ${q(hex(colors, "gray"))}`,
        `    line-numbers-left-style = ${q(hex(colors, "bg2"))}`,
        `    line-numbers-right-style = ${q(hex(colors, "bg2"))}`,
        `    file-style = bold ${q(hex(colors, "accentLight"))}`,
        "    file-decoration-style = none",
        `    hunk-header-style = file line-number syntax`,
        `    hunk-header-decoration-style = ${q(hex(colors, "bg2"))} box`
    ]
    return lines.join("\n") + "\n"
}
